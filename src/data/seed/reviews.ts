import type { Review } from '../../domain/models/review';

/**
 * MOCK REVIEWS. Every review here is made-up sample data for the prototype (see the "What’s
 * pretend" list in the first-visit notice). Each stylist has at least 50, newest first, mostly 4
 * and 5 stars with a few 3s, and dates over the two years before this file was written
 * (late November 2024 to mid-November 2026). A stylist’s average rating is computed from these,
 * so changing a row here changes her rating everywhere with no other edit.
 *
 * Each row is [name, stars, date, comment]. Names are a first name and last initial.
 */
type Row = readonly [name: string, stars: number, date: string, text: string];

function rows(stylistId: string, list: readonly Row[]): readonly Review[] {
  return list.map(([name, stars, date, text], index) => ({
    id: `${stylistId}-${index + 1}`,
    name,
    stars,
    date,
    text,
  }));
}

